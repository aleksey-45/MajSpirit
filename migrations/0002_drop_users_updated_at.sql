-- 删掉 users.updated_at。
--
-- 它从建立起就没被写过：全仓没有任何 UPDATE users，也没有触发器，
-- 所以它的值永远等于 created_at —— 一个叫「最后更新时间」的列，
-- 说的其实是创建时间，而且不会报错。
--
-- 修法有二：加 BEFORE UPDATE 触发器让它成真，或者删掉它。
-- 选删：改密码功能还不存在，为一条不存在的代码路径维护触发器属于凭空造需求。
-- 将来真加了改密码，那时再加列 + 触发器 —— 那时候也才知道该更新哪些字段。
--
-- 为什么单开一个文件而不是直接改 0001：
-- 0001 已经在两个库的 schema_migrations 里记过账了，改它不会被重跑，
-- 于是「新建的库」和「现有的库」结构会分叉 —— 那正是迁移要消灭的东西。
-- 迁移一旦应用过就不可变，只能往后追加。

ALTER TABLE users DROP COLUMN updated_at;
