// Package room 实现房间与对局的调度，对应任务书 §4 与 §5。
//
// 并发模型：每个房间由一个独立的 goroutine 独占其全部状态（座位、牌山、手牌、
// 当前回合）。外部不直接读写房间状态，而是通过 channel 投递指令，由该 goroutine
// 串行处理——这样从根上消除了"四个玩家并发操作同一局牌"的竞态，不需要给共享状态
// 加锁。
//
// 职责：
//   - Hub：房间的创建、查询与销毁
//   - Room：四个座位、加入与离开、开局条件（满四人）
//   - Game：一场的推进 —— 洗牌发牌、摸牌打牌、鸣牌（吃/碰/杠）、立直宣告、
//     和牌与荒牌流局判定、连庄与本场、帕奥责任者跟踪、顺位结算
//
// 规则的判定全部委托给 internal/mahjong；本包只负责调度与状态流转，不实现任何
// 役种、符数或点数计算。
//
// M-League 引入的鸣牌、立直宣告、抢杠会让摸打循环被打断，这些等待必须带超时，
// 否则一个掉线玩家就能卡死整局。
//
// 两条实现上的约束：
//   - 帕奥责任者必须在鸣牌那一刻记下，不能等和牌时回头算——那时手牌已经变了。
//   - 顺位点（ポイント）在整场结束后算一次，不进 internal/mahjong。
//
// 对外通信通过接口回调，不直接依赖 WebSocket。
