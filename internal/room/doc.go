// Package room 实现房间与对局的调度，对应任务书 §4 与 §5。
//
// 并发模型：每个房间由一个独立的 goroutine 独占其全部状态（座位、牌山、
// 手牌、当前回合）。外部不直接读写房间状态，而是通过 channel 投递指令，
// 由该 goroutine 串行处理。这样从根上消除了「四个玩家并发操作同一局牌」
// 的竞态，不需要给共享状态加锁。
//
// 职责：
//   - Hub：房间的创建、查询与销毁
//   - Room：四个座位、加入与离开、开局条件（满四人）
//   - Game：一场四小局的推进 —— 洗牌发牌、摸牌打牌、鸣牌（吃/碰/杠）、
//     立直宣告、和牌与流局判定、连庄与本场、顺位结算
//
// 规则的判定全部委托给 internal/mahjong；本包只负责调度与状态流转，
// 不实现任何役种、符数或点数计算。
//
// 完整立直麻将引入了「他家打牌后可鸣牌」「立直宣言」「一炮多响」等
// 需要等待玩家响应的时机，房间状态机因此比简化规则复杂得多：
// 摸打循环会被鸣牌/和牌/立直的询问打断。这些等待必须带超时，
// 否则一个掉线玩家就能卡死整局。
//
// 对外通信通过接口回调，不直接依赖 WebSocket，便于脱离网络做测试。
