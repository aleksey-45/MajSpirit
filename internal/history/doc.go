// Package history 是历史牌局的用例层：读过往牌局，以及（阶段五后半）把打完的
// 一场落库。
//
// 它在依赖链上与 internal/user 同位置：
//
//	cmd/server → api ──→ history ──→ store ──→ migrations
//
// 存在的理由有两条，都不是"抽象好看"：
//
//   - api 不许 import store（分层硬约束），所以两者之间需要一个只认自己词汇的层。
//     它是唯一决定响应体里那几种表示的地方：毫秒时间戳、hex 字节、JSONB 原样透出。
//   - 写路径要在这里做有界队列 + 重试 + 种子/承诺生成（阶段五后半）。那几件事塞进
//     cmd/server 就没法单测，塞进 store 会让数据层开始管 goroutine。
//
// 它不做的事：不做回放（不替玩家重算牌山），不做统计聚合，不碰 HTTP。
// 承诺值与种子照旧入库并随单局详情下发，所以"你可以自己验证"这条仍然成立。
