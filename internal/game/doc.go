// Package game 实现一场对局的推进：发牌、摸打、等待鸣牌、和了与流局、连庄、顺位。
//
// 它是一个**独立的 actor**：一个 goroutine 独占全部对局状态，外部只往 channel 投指令。
// 与 `internal/room` 的分工是：
//
//	room  谁坐在哪、连着没连着、能不能开局
//	game  这一手谁打、谁在和什么、这局怎么算
//
// 两边只通过一个方向来往：game 用 Notifier 往外发事件，打完一场用 OnEnd 回调通知房间
// （回调里只投一条指令，不碰房间状态）。房间不读对局的任何字段。
//
// **规则判定一律委托 internal/mahjong**：这里只决定"谁在什么时候可以做什么"，
// 不自己算役、符、点。
//
// 还没做的见 docs/local/阶段四-对局.md：吃/碰/杠、立直、宝牌翻牌、一发/岭上/抢杠/海底、
// 帕奥责任者、game.sync 快照。
