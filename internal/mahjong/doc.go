// Package mahjong 实现立直麻将的纯规则逻辑。
//
// 本项目采用 M.LEAGUE（Mリーグ）公式戦ルール（任务书 §7 的加分项内容），
// 不是 §5 描述的简化版，也不是"自定村规"。
// 规则与算点的权威依据是仓库里的 docs/规则集.md —— 实现与测试都以它为准，
// 每条结论都标注了出处（【M】M-League 原文 /【連】连盟 /【慣】社区惯例）。
//
// 本包刻意不引入任何 IO、网络、数据库依赖：所有函数都应当是纯函数，或只操作
// 自身状态，以便被完整单元测试覆盖。上层的房间调度与 WebSocket 通信都不应该
// 把逻辑漏到这里，也不应该把这里的规则复制到别处。
//
// 已实现：
//
//   - 牌的表示与编解码：34 种牌，编码 0..33
//     （0-8 万、9-17 条、18-26 饼、27-33 字牌），每种 4 张，共 136 张
//   - 紧凑记法：形如 "123m456s789p11z" 的解析与格式化，
//     供测试用例、日志与数据库共用同一套表示。
//     赤宝牌写作 0m / 0s / 0p（数字 0 表示该花色的红 5），用**额外的编号**
//     34/35/36 表示；它与 5m 种类相同，规则判定一律先过 Tile.Kind()
//   - 牌山：确定性洗牌、摸牌、给四家各发 13 张初始手牌（庄家的第 14 张
//     作为它的第一次摸牌），以及余牌判断
//   - 手牌与副露：增删、计数、排序
//   - 和牌型判定：4 面子 + 1 雀头、七对子、国士无双（Decompose 返回全部拆法）
//   - 役种判定：全部役种的成立判定与翻数（门清/副露两列），
//     门清限定役在副露后完全不成立
//   - 符数计算：副底、面子、雀头、待ち、自摸、门清荣和；
//     七对子固定 25 符、平和自摸固定 20 符
//   - 宝牌：指示牌到宝牌的映射（风牌与三元牌是两个独立循环）、
//     表/里/赤宝牌的计数；宝牌不算役，役满时不计
//   - 点数换算：基本点、满贯封顶、切上满贯、各家收支与取整
//   - 规则变体：把各地规则差异收敛成一个 Rules 结构体，
//     而不是散落各处的条件分支
//
// 还缺：
//
//   - Waits / IsTenpai：振听、听牌料、立直合法性三处都依赖它
//   - 吃、碰、杠的成立判定，与立直宣言的合法性
//   - **把 ①–⑨ 串起来的入口**：和牌形 → 有役 → 非振听 → 选最高拆法 →
//     役 → 加宝牌 → 符 → 基本点 → 收支。宝牌是第 ⑥ 步，
//     放在役之前会做出「只有宝牌也能和牌」的游戏
//   - verify.go：牌山可验证性（承诺、派生、指纹）
//
// 建议按「役种判定 / 符数计算 / 点数换算」三块拆分，彼此不互相依赖，
// 这样每一块都能独立测试，出错时能迅速定位是哪一层的责任。
